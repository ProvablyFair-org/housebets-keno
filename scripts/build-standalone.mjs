#!/usr/bin/env node
// Generates verify.js: tests/verify.ts and everything it imports in one plain-JavaScript file, so `node verify.js` runs the
// whole suite on Node 22 with nothing installed and no TypeScript flags. Built with Bun's bundler (auditor tooling only;
// the output needs nothing but Node). verify.js reads data/, evidence/ and outputs/ from the folder it sits in.
// Staleness guard: STANDALONE.json pins the sha256 of every source input (every src/*.ts and tests/verify.ts) and of
// the generated verify.js. The same source map is embedded at the top of verify.js, which re-derives it from disk before
// anything else runs and refuses to run (exit 4) when a source differs: a bundle is evidence only if it provably came from
// the sources a reader can read. The verifier's fresh-copy step (<GAME>-28) re-checks both pins.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const sha = (b) => createHash('sha256').update(b).digest('hex');
// scripts/fingerprint.mjs is bundled too (KENO-28/29 record binding), so the guard pins it as well
const inputs = [...readdirSync(join(ROOT, 'src')).filter((f) => f.endsWith('.ts')).sort().map((f) => `src/${f}`), 'tests/verify.ts', 'scripts/fingerprint.mjs'];
const sources = Object.fromEntries(inputs.map((p) => [p, sha(readFileSync(join(ROOT, p)))]));
const bun = spawnSync('bun', ['--version'], { encoding: 'utf8' }).stdout.trim();
const r = spawnSync('bun', ['build', 'tests/verify.ts', '--target=node', '--format=esm', '--outfile=verify.js.tmp'], { cwd: ROOT, encoding: 'utf8' });
if (r.status !== 0) { console.error(r.stdout, r.stderr); process.exit(1); }
const body = readFileSync(join(ROOT, 'verify.js.tmp'), 'utf8');
const header = `/**
 * STANDALONE VERIFIER — generated by scripts/build-standalone.mjs from tests/verify.ts, do not edit.
 *
 *     node verify.js
 *
 * Node 22, nothing to install. STALENESS GUARD: the sources this file was built from are pinned below and in STANDALONE.json;
 * it re-derives them from disk first and refuses to run when any differs (rebuild: npm run build:standalone).
 */
import { readFileSync as __pfRead, existsSync as __pfExists } from 'node:fs';
import { createHash as __pfHash } from 'node:crypto';
import { join as __pfJoin, dirname as __pfDir } from 'node:path';
import { fileURLToPath as __pfPath } from 'node:url';
const __pfSources = ${JSON.stringify(sources, null, 2)};
{
  const root = __pfDir(__pfPath(import.meta.url));
  const stale = Object.entries(__pfSources).filter(([p, h]) => !__pfExists(__pfJoin(root, p)) || __pfHash('sha256').update(__pfRead(__pfJoin(root, p))).digest('hex') !== h).map(([p]) => p);
  if (stale.length) { console.error('STALENESS GUARD: verify.js was not built from the sources in this folder (' + stale.join(', ') + '); rebuild with npm run build:standalone'); process.exit(4); }
}
// the guard also hashes this file's own generated body (everything after the marker line below) against the
// sha256 the build wrote here and in STANDALONE.json, so an edited body exits 4 too
const __pfBodySha = '${sha(body)}';
{
  const self = __pfRead(__pfPath(import.meta.url), 'utf8'); const mark = '/*__PF_' + 'BODY__*/\\n'; const i = self.lastIndexOf(mark);
  if (i < 0 || __pfHash('sha256').update(self.slice(i + mark.length)).digest('hex') !== __pfBodySha) { console.error('STALENESS GUARD: the body of verify.js is not the one built from these sources; rebuild with npm run build:standalone'); process.exit(4); }
}
/*__PF_BODY__*/
`;
const out = header + body;
writeFileSync(join(ROOT, 'verify.js'), out);
rmSync(join(ROOT, 'verify.js.tmp'), { force: true });
const manifest = { generator: 'scripts/build-standalone.mjs', bundler: `bun ${bun}`, entry: 'tests/verify.ts', sources, body: sha(body), output: { 'verify.js': sha(out) } };
writeFileSync(join(ROOT, 'STANDALONE.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`wrote verify.js (${out.length} chars, sha256 ${sha(out)}) and STANDALONE.json (${inputs.length} sources)`);
